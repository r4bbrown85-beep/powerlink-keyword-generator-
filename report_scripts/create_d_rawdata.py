def fmt_head(bg, bold=True, font_size=10, fg=rgb(255,255,255)):
    return {
        'backgroundColor': bg,
        'textFormat': {'bold': bold, 'fontSize': font_size, 'foregroundColor': fg},
        'verticalAlignment': 'MIDDLE',
        'wrapStrategy': 'WRAP',
    }

def fmt_body(bg):
    return {
        'backgroundColor': bg,
        'textFormat': {'bold': False, 'fontSize': 9, 'foregroundColor': rgb(30,30,30)},
        'verticalAlignment': 'TOP',
        'wrapStrategy': 'WRAP',
    }

def cell_req(sid, r, c, val, fmt):
    return {
        'updateCells': {
            'rows': [{'values': [{'userEnteredValue': {'stringValue': str(val)},
                                  'userEnteredFormat': fmt}]}],
            'fields': 'userEnteredValue,userEnteredFormat',
            'range': {'sheetId': sid, 'startRowIndex': r, 'endRowIndex': r+1,
                      'startColumnIndex': c, 'endColumnIndex': c+1}
        }
    }

def col_width(sid, c_idx, px):
    return {'updateDimensionProperties': {
        'range': {'sheetId': sid, 'dimension': 'COLUMNS',
                  'startIndex': c_idx, 'endIndex': c_idx+1},
        'properties': {'pixelSize': px}, 'fields': 'pixelSize'}}

def row_height(sid, r_idx, px):
    return {'updateDimensionProperties': {
        'range': {'sheetId': sid, 'dimension': 'ROWS',
                  'startIndex': r_idx, 'endIndex': r_idx+1},
        'properties': {'pixelSize': px}, 'fields': 'pixelSize'}}

def freeze_req(sid, rows=1, cols=2):
    return {'updateSheetProperties': {
        'properties': {'sheetId': sid, 'gridProperties': {
            'frozenRowCount': rows, 'frozenColumnCount': cols}},
        'fields': 'gridProperties.frozenRowCount,gridProperties.frozenColumnCount'}}

def build_sheet(title, rows_data):
    """
    rows_data: list of tuples (row_type, src_tag, col_a_text, col_c_text)
      row_type: 'MAIN_HEAD' | 'SEC_HEAD' | 'DATA'
    """
    # 기존 시트 삭제 후 재생성
    for ws in wb.worksheets():
        if ws.title == title:
            wb.del_worksheet(ws)
            time.sleep(1)
    ws = wb.add_worksheet(title=title, rows=len(rows_data)+5, cols=4)
    sid = ws.id
    reqs = []

    # 컬럼 너비
    reqs += [col_width(sid,0,120), col_width(sid,1,100), col_width(sid,2,650), col_width(sid,3,80)]
    # 헤더행 높이
    reqs.append(row_height(sid,0,40))
    # freeze
    reqs.append(freeze_req(sid,1,2))

    # 헤더 행
    hdr_fmt = fmt_head(C_HEAD, bold=True, font_size=10)
    for ci, txt in enumerate(['섹션/구분','출처','내용/데이터','비고']):
        reqs.append(cell_req(sid,0,ci,txt,hdr_fmt))

    for ri, (rtype, src, col_a, col_c) in enumerate(rows_data, start=1):
        reqs.append(row_height(sid, ri, 18 if rtype=='DATA' else 24))
        if rtype == 'MAIN_HEAD':
            bg = C_HEAD
            fg_col = rgb(255,255,255)
            f = fmt_head(bg, bold=True, font_size=10, fg=fg_col)
            reqs.append(cell_req(sid,ri,0,col_a,f))
            reqs.append(cell_req(sid,ri,1,'',f))
            reqs.append(cell_req(sid,ri,2,col_c,f))
            reqs.append(cell_req(sid,ri,3,'',f))
        elif rtype == 'SEC_HEAD':
            bg = C_SEC
            f = fmt_head(bg, bold=True, font_size=9, fg=rgb(255,255,255))
            reqs.append(cell_req(sid,ri,0,col_a,f))
            reqs.append(cell_req(sid,ri,1,src,f))
            reqs.append(cell_req(sid,ri,2,col_c,f))
            reqs.append(cell_req(sid,ri,3,'',f))
        else:  # DATA
            bg = SRC_COLOR.get(src, C_WHITE)
            f = fmt_body(bg)
            reqs.append(cell_req(sid,ri,0,col_a,f))
            reqs.append(cell_req(sid,ri,1,src,f))
            reqs.append(cell_req(sid,ri,2,col_c,f))
            reqs.append(cell_req(sid,ri,3,'',f))

    # 배치 실행 (200개씩 분할)
    batch_size = 200
    for i in range(0, len(reqs), batch_size):
        wb.batch_update({'requests': reqs[i:i+batch_size]})
        time.sleep(0.5)
    print(f"  ✓ [{title}] 완료 ({len(rows_data)}행)")
    return sid


