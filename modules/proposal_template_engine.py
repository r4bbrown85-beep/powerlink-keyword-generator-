def select_category_template(profile):
    """
    업종 기준으로 제안서형 카테고리 템플릿 선택
    """
    industry = (profile.get("industry", "") or "").strip()
    products = profile.get("products", []) or []

    text = f"{industry} {' '.join(products)}"

    # 자동차/중고차 계열
    if any(x in text for x in ["중고차", "차량", "자동차", "차종"]):
        return [
            "브랜드 키워드",
            "일반 키워드",
            "경쟁사 키워드",
            "차종 키워드",
            "지역 키워드",
            "가격/비용 키워드",
            "후기/비교 키워드"
        ]

    # 골프/레슨 계열
    if any(x in text for x in ["골프", "레슨", "연습장", "피팅", "스크린골프"]):
        return [
            "브랜드 키워드",
            "일반 키워드",
            "경쟁사 키워드",
            "레슨 유형 키워드",
            "지역 키워드",
            "가격/비용 키워드",
            "후기/비교 키워드",
            "예약/문의 키워드"
        ]

    # 병원/치과/클리닉 계열
    if any(x in text for x in ["병원", "치과", "의원", "클리닉", "성형", "피부과"]):
        return [
            "브랜드 키워드",
            "일반 키워드",
            "경쟁사 키워드",
            "진료/시술 키워드",
            "지역 키워드",
            "가격/비용 키워드",
            "후기/비교 키워드",
            "상담/예약 키워드"
        ]

    # 기본 템플릿
    return [
        "브랜드 키워드",
        "일반 키워드",
        "경쟁사 키워드",
        "제품/서비스 키워드",
        "지역 키워드",
        "가격/비용 키워드",
        "후기/비교 키워드",
        "예약/문의 키워드"
    ]


